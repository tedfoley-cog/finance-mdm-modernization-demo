"""Self-contained HTML report (no CDN): layered dependency map + impact / duplicate / drift tables."""

from __future__ import annotations

import html
import json

from .model import LAYER_ORDER, Graph
from .queries import DriftReport, DupeGroup, ImpactReport

LAYER_LABEL = {
    "ui": "React UI",
    "api": "FastAPI",
    "schema": "Pydantic schemas",
    "db": "RDS / Alembic",
    "pipeline": "PySpark jobs",
    "source": "Source contracts",
    "warehouse": "Snowflake",
    "infra": "Terraform / AWS",
    "config": "Runtime config",
    "legacy": "Legacy batch",
    "test": "Tests",
}
CSS = """body{font-family:system-ui,Segoe UI,sans-serif;margin:0;color:#1b2430;background:#f6f7f9}header{background:#14233a;color:#fff;padding:14px 24px}
main{padding:20px 24px;max-width:1400px;margin:auto}section{background:#fff;border:1px solid #d9dee5;border-radius:4px;padding:14px 18px;margin-bottom:18px}
h1{font-size:18px;margin:0}h2{font-size:15px;margin:0 0 10px}table{border-collapse:collapse;width:100%;font-size:13px}th,td{text-align:left;padding:5px 8px;border-bottom:1px solid #e5e8ec;vertical-align:top}
th{color:#5b6774;font-size:12px}code{font-family:ui-monospace,Menlo,monospace;font-size:12px}.w{display:inline-block;padding:0 6px;border-radius:9px;background:#eef3fa;color:#0b5fa5;font-size:11px}
.bad{background:#fdf2f2;color:#b91c1c}.ok{background:#effaf2;color:#15803d}.layer{font-weight:600;color:#0b5fa5}svg text{font-size:10px;font-family:ui-monospace,monospace}
.muted{color:#5b6774}"""


def _esc(s: object) -> str:
    return html.escape(str(s))


def _svg_map(g: Graph, highlight: set[str]) -> str:
    cols = [layer for layer in LAYER_ORDER if any(n.layer == layer for n in g.nodes.values()) and layer != "test"]
    nodes = {
        layer: sorted(
            [n for n in g.nodes.values() if n.layer == layer and n.kind not in {"column", "field", "literal", "expectation"}],
            key=lambda n: n.name,
        )
        for layer in cols
    }
    col_w, row_h, left, top = 220, 16, 20, 30
    pos = {}
    height = top + row_h * max(len(v) for v in nodes.values()) + 20
    out = [f'<svg width="{left + col_w * len(cols)}" height="{height}" xmlns="http://www.w3.org/2000/svg">']
    for ci, layer in enumerate(cols):
        x = left + ci * col_w
        out.append(f'<text x="{x}" y="16" style="font-weight:600;font-size:12px;fill:#0b5fa5">{_esc(LAYER_LABEL.get(layer, layer))}</text>')
        for ri, n in enumerate(nodes[layer]):
            y = top + ri * row_h
            pos[n.id] = (x, y)
            fill = "#b91c1c" if n.id in highlight else "#1b2430"
            weight = "font-weight:600;" if n.id in highlight else ""
            label = n.name if len(n.name) <= 34 else n.name[:33] + "…"
            out.append(
                f'<text x="{x}" y="{y + 10}" style="fill:{fill};{weight}"><title>{_esc(n.id)} — {_esc(n.path)}:{n.line}</title>{_esc(label)}</text>'
            )
    for e in g.edges:
        if e.src in pos and e.dst in pos:
            (x1, y1), (x2, y2) = pos[e.src], pos[e.dst]
            hot = e.src in highlight and e.dst in highlight
            out.append(
                f'<line x1="{x1 + 200}" y1="{y1 + 6}" x2="{x2}" y2="{y2 + 6}" stroke="{"#b91c1c" if hot else "#c9d1da"}" stroke-width="{1.6 if hot else 0.6}" opacity="{0.9 if hot else 0.5}"><title>{_esc(e.kind)}</title></line>'
            )
    out.append("</svg>")
    return "".join(out)


def render(
    g: Graph,
    impact: ImpactReport | None = None,
    dupes: list[DupeGroup] | None = None,
    drifts: list[DriftReport] | None = None,
    title: str = "LedgerCore MDM dependency map",
) -> str:
    hl = {h.node.id for h in impact.hits} if impact else set()
    parts = [
        f"<!doctype html><html><head><meta charset='utf-8'><title>{_esc(title)}</title><style>{CSS}</style></head><body>",
        f"<header><h1>{_esc(title)}</h1><div class='muted' style='color:#c9d6e8'>{len(g.nodes)} nodes · {len(g.edges)} edges · generated by tools/depgraph</div></header><main>",
    ]
    if impact:
        parts.append(
            f"<section><h2>Impact: <code>{_esc(impact.term)}</code> — {len(impact.hits)} affected nodes across {len(impact.by_layer())} layers</h2>"
        )
        if impact.width_conflicts:
            parts.append(
                "<p><span class='w bad'>width mismatch</span> seeds disagree on the field width: "
                + ", ".join(f"<code>{_esc(n.name)}</code>={_esc(n.attrs.get('width'))}" for n in impact.width_conflicts)
                + "</p>"
            )
        parts.append("<table><tr><th>Layer</th><th>Node</th><th>Kind</th><th>Where</th><th>Attrs</th><th>Reached via</th></tr>")
        for layer, hits in impact.by_layer().items():
            for h in hits:
                attrs = " ".join(
                    f"<span class='w'>{_esc(k)}={_esc(v)}</span>" for k, v in h.node.attrs.items() if v is not None and k != "per_env"
                )
                via = "seed" if h.depth == 0 else f"{_esc(h.via)} ← <code>{_esc(h.from_id)}</code>"
                parts.append(
                    f"<tr><td class='layer'>{_esc(LAYER_LABEL.get(layer, layer))}</td><td><code>{_esc(h.node.name)}</code></td><td>{_esc(h.node.kind)}</td>"
                    f"<td><code>{_esc(h.node.path)}:{h.node.line}</code></td><td>{attrs}</td><td>{via}</td></tr>"
                )
        parts.append("</table></section>")
    if dupes:
        parts.append("<section><h2>Duplicated logic</h2><table><tr><th>Concept</th><th>Copies</th><th>Variants</th><th>Members</th></tr>")
        for d in dupes:
            badge = "<span class='w bad'>divergent</span>" if d.divergent else "<span class='w ok'>consistent</span>"
            members = "<br>".join(
                f"<code>{_esc(m.id)}</code> <span class='muted'>{_esc(m.path)}:{m.line}</span> <code>{_esc(m.attrs.get('regex') or m.attrs.get('width') or '')}</code>"
                for m in d.members
            )
            parts.append(
                f"<tr><td>{_esc(d.concept)}</td><td>{len(d.members)}</td><td>{len(d.variants)} {badge}</td><td>{members}</td></tr>"
            )
        parts.append("</table></section>")
    if drifts:
        for dr in drifts:
            parts.append(
                f"<section><h2>Drift: <code>{_esc(dr.env)}</code> vs <code>{_esc(dr.base)}</code> — {len(dr.commits_ahead)} commits not on {_esc(dr.base)}</h2>"
            )
            parts.append("<ul>" + "".join(f"<li><code>{_esc(c)}</code></li>" for c in dr.commits_ahead) + "</ul>")
            parts.append("<table><tr><th>Status</th><th>File</th><th>Graph nodes</th></tr>")
            for status, path in dr.files:
                ns = (
                    ", ".join(f"<code>{_esc(n.id)}</code>" for n in dr.touched_nodes if n.path == path)
                    or "<span class='muted'>config only</span>"
                )
                parts.append(f"<tr><td>{_esc(status)}</td><td><code>{_esc(path)}</code></td><td>{ns}</td></tr>")
            parts.append("</table></section>")
    parts.append(f"<section><h2>Cross-stack map</h2><div style='overflow:auto'>{_svg_map(g, hl)}</div></section>")
    parts.append(
        f"<script type='application/json' id='graph'>{json.dumps({'nodes': len(g.nodes), 'edges': len(g.edges)})}</script></main></body></html>"
    )
    return "".join(parts)
