-- Landing -> curated refresh. The external stage points at the publish bucket written by the steward API
-- (infra/terraform/s3.tf); the Lambda notifier (infra/terraform/lambda/publish_notifier.py) calls
-- SYSTEM$TASK... via the Snowflake REST API after each publish so the task does not have to poll.

CREATE STAGE IF NOT EXISTS FDP_MDM.LANDING.STG_MDM_PUBLISH
    URL = 's3://ledgercore-mdm-publish-prod/golden/'
    STORAGE_INTEGRATION = SI_LEDGERCORE_MDM
    FILE_FORMAT = (TYPE = JSON);

CREATE OR REPLACE PROCEDURE FDP_MDM.UTIL.SP_LOAD_COST_CENTERS(RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    COPY INTO FDP_MDM.LANDING.COST_CENTER_RAW
        (ENTITY_CODE, COST_CENTER_CODE, DESCRIPTION, PARENT_COST_CENTER_CODE, MANAGER_EMPLOYEE_ID,
         PROFIT_CENTER_CODE, STATUS, SOURCE_SYSTEM, PUBLISH_RUN_ID)
    FROM (SELECT $1:entity_code, $1:cost_center_code, $1:description, $1:parent_cost_center_code,
                 $1:manager_employee_id, $1:profit_center_code, $1:status, $1:source_system, :RUN_ID
          FROM @FDP_MDM.LANDING.STG_MDM_PUBLISH/cost_center/)
    PATTERN = '.*' || :RUN_ID || '.jsonl';

    MERGE INTO FDP_MDM.CURATED.DIM_COST_CENTER t
    USING (
        SELECT * FROM FDP_MDM.LANDING.COST_CENTER_RAW WHERE PUBLISH_RUN_ID = :RUN_ID
    ) s
    ON t.ENTITY_CODE = s.ENTITY_CODE AND t.COST_CENTER_CODE = s.COST_CENTER_CODE
    WHEN MATCHED THEN UPDATE SET
        DESCRIPTION = s.DESCRIPTION,
        PARENT_COST_CENTER_CODE = s.PARENT_COST_CENTER_CODE,
        DIVISION_CODE = SUBSTR(s.COST_CENTER_CODE, 1, 3),
        MANAGER_EMPLOYEE_ID = s.MANAGER_EMPLOYEE_ID,
        PROFIT_CENTER_CODE = s.PROFIT_CENTER_CODE,
        STATUS = s.STATUS,
        SOURCE_SYSTEM = s.SOURCE_SYSTEM,
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT
        (ENTITY_CODE, COST_CENTER_CODE, DESCRIPTION, PARENT_COST_CENTER_CODE, DIVISION_CODE,
         MANAGER_EMPLOYEE_ID, PROFIT_CENTER_CODE, STATUS, SOURCE_SYSTEM, EFFECTIVE_FROM, UPDATED_AT)
    VALUES
        (s.ENTITY_CODE, s.COST_CENTER_CODE, s.DESCRIPTION, s.PARENT_COST_CENTER_CODE,
         SUBSTR(s.COST_CENTER_CODE, 1, 3), s.MANAGER_EMPLOYEE_ID, s.PROFIT_CENTER_CODE, s.STATUS,
         s.SOURCE_SYSTEM, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());
    RETURN 'OK';
END;
$$;

CREATE OR REPLACE PROCEDURE FDP_MDM.UTIL.SP_LOAD_VENDORS(RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    COPY INTO FDP_MDM.LANDING.VENDOR_RAW
        (VENDOR_ID, LEGAL_NAME, TAX_ID, TAX_ID_NORMALIZED, COUNTRY_CODE, PAYMENT_TERMS,
         DEFAULT_COST_CENTER_CODE, STATUS, GOLDEN_RECORD_ID, SOURCE_SYSTEM, PUBLISH_RUN_ID)
    FROM (SELECT $1:vendor_id, $1:legal_name, $1:tax_id, $1:tax_id_normalized, $1:country_code,
                 $1:payment_terms, $1:default_cost_center_code, $1:status, $1:golden_record_id,
                 $1:source_system, :RUN_ID
          FROM @FDP_MDM.LANDING.STG_MDM_PUBLISH/vendor/)
    PATTERN = '.*' || :RUN_ID || '.jsonl';

    MERGE INTO FDP_MDM.CURATED.DIM_VENDOR t
    USING (SELECT * FROM FDP_MDM.LANDING.VENDOR_RAW WHERE PUBLISH_RUN_ID = :RUN_ID) s
    ON t.VENDOR_ID = s.VENDOR_ID
    WHEN MATCHED THEN UPDATE SET
        GOLDEN_RECORD_ID = s.GOLDEN_RECORD_ID,
        LEGAL_NAME = s.LEGAL_NAME,
        TAX_ID_NORMALIZED = COALESCE(s.TAX_ID_NORMALIZED, FDP_MDM.UTIL.FN_NORMALIZE_TAX_ID(s.TAX_ID)),
        COUNTRY_CODE = s.COUNTRY_CODE,
        PAYMENT_TERMS = s.PAYMENT_TERMS,
        DEFAULT_COST_CENTER_CODE = s.DEFAULT_COST_CENTER_CODE,
        STATUS = s.STATUS,
        SOURCE_SYSTEM = s.SOURCE_SYSTEM,
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT
        (VENDOR_ID, GOLDEN_RECORD_ID, LEGAL_NAME, TAX_ID_NORMALIZED, COUNTRY_CODE, PAYMENT_TERMS,
         DEFAULT_COST_CENTER_CODE, STATUS, SOURCE_SYSTEM, UPDATED_AT)
    VALUES
        (s.VENDOR_ID, s.GOLDEN_RECORD_ID, s.LEGAL_NAME,
         COALESCE(s.TAX_ID_NORMALIZED, FDP_MDM.UTIL.FN_NORMALIZE_TAX_ID(s.TAX_ID)), s.COUNTRY_CODE,
         s.PAYMENT_TERMS, s.DEFAULT_COST_CENTER_CODE, s.STATUS, s.SOURCE_SYSTEM, CURRENT_TIMESTAMP());
    RETURN 'OK';
END;
$$;

-- Nightly safety net in case the event-driven path missed a publish.
CREATE OR REPLACE TASK FDP_MDM.UTIL.TASK_NIGHTLY_REFRESH
    WAREHOUSE = FDP_TRANSFORM_WH
    SCHEDULE = 'USING CRON 0 2 * * * America/Chicago'
AS
    CALL FDP_MDM.UTIL.SP_LOAD_COST_CENTERS(TO_VARCHAR(CURRENT_DATE(), 'YYYYMMDD') || 'T000000Z');
