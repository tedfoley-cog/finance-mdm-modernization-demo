-- Landing tables mirror the JSONL published by api/app/services/publish.py (one row per golden record).
-- Column widths must match api/app/models.py and the RDS schema in api/alembic/versions.

CREATE TABLE IF NOT EXISTS FDP_MDM.LANDING.COST_CENTER_RAW (
    ENTITY_CODE              VARCHAR(4)   NOT NULL,
    COST_CENTER_CODE         VARCHAR(6)   NOT NULL,
    DESCRIPTION              VARCHAR(120),
    PARENT_COST_CENTER_CODE  VARCHAR(6),
    MANAGER_EMPLOYEE_ID      VARCHAR(12),
    PROFIT_CENTER_CODE       VARCHAR(10),
    STATUS                   VARCHAR(16),
    SOURCE_SYSTEM            VARCHAR(20),
    PUBLISH_RUN_ID           VARCHAR(32)  NOT NULL,
    LOADED_AT                TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FDP_MDM.LANDING.VENDOR_RAW (
    VENDOR_ID                 VARCHAR(10)  NOT NULL,
    LEGAL_NAME                VARCHAR(200),
    TAX_ID                    VARCHAR(32),
    TAX_ID_NORMALIZED         VARCHAR(32),
    COUNTRY_CODE              VARCHAR(2),
    PAYMENT_TERMS             VARCHAR(8),
    DEFAULT_COST_CENTER_CODE  VARCHAR(6),
    STATUS                    VARCHAR(16),
    GOLDEN_RECORD_ID          VARCHAR(36),
    SOURCE_SYSTEM             VARCHAR(20),
    PUBLISH_RUN_ID            VARCHAR(32)  NOT NULL,
    LOADED_AT                 TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FDP_MDM.LANDING.GL_ACCOUNT_RAW (
    ACCOUNT_NUMBER   VARCHAR(8) NOT NULL,
    DESCRIPTION      VARCHAR(120),
    ACCOUNT_TYPE     VARCHAR(16),
    NORMAL_BALANCE   VARCHAR(2),
    STATUS           VARCHAR(16),
    PUBLISH_RUN_ID   VARCHAR(32) NOT NULL,
    LOADED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Curated: one current row per business key (type-1), maintained by the MERGE task in 030_tasks.sql.
CREATE TABLE IF NOT EXISTS FDP_MDM.CURATED.DIM_COST_CENTER (
    COST_CENTER_SK           NUMBER(38,0) AUTOINCREMENT,
    ENTITY_CODE              VARCHAR(4)   NOT NULL,
    COST_CENTER_CODE         VARCHAR(6)   NOT NULL,
    DESCRIPTION              VARCHAR(120),
    PARENT_COST_CENTER_CODE  VARCHAR(6),
    DIVISION_CODE            VARCHAR(3),
    MANAGER_EMPLOYEE_ID      VARCHAR(12),
    PROFIT_CENTER_CODE       VARCHAR(10),
    STATUS                   VARCHAR(16),
    SOURCE_SYSTEM            VARCHAR(20),
    EFFECTIVE_FROM           TIMESTAMP_NTZ,
    UPDATED_AT               TIMESTAMP_NTZ,
    CONSTRAINT PK_DIM_COST_CENTER PRIMARY KEY (ENTITY_CODE, COST_CENTER_CODE)
);

CREATE TABLE IF NOT EXISTS FDP_MDM.CURATED.DIM_VENDOR (
    VENDOR_SK                 NUMBER(38,0) AUTOINCREMENT,
    VENDOR_ID                 VARCHAR(10)  NOT NULL,
    GOLDEN_RECORD_ID          VARCHAR(36),
    LEGAL_NAME                VARCHAR(200),
    TAX_ID_NORMALIZED         VARCHAR(32),
    COUNTRY_CODE              VARCHAR(2),
    PAYMENT_TERMS             VARCHAR(8),
    DEFAULT_COST_CENTER_CODE  VARCHAR(6),
    STATUS                    VARCHAR(16),
    SOURCE_SYSTEM             VARCHAR(20),
    UPDATED_AT                TIMESTAMP_NTZ,
    CONSTRAINT PK_DIM_VENDOR PRIMARY KEY (VENDOR_ID)
);

CREATE TABLE IF NOT EXISTS FDP_MDM.CURATED.DIM_GL_ACCOUNT (
    ACCOUNT_NUMBER   VARCHAR(8) NOT NULL,
    DESCRIPTION      VARCHAR(120),
    ACCOUNT_TYPE     VARCHAR(16),
    NORMAL_BALANCE   VARCHAR(2),
    STATUS           VARCHAR(16),
    UPDATED_AT       TIMESTAMP_NTZ,
    CONSTRAINT PK_DIM_GL_ACCOUNT PRIMARY KEY (ACCOUNT_NUMBER)
);

-- Match/merge output from pipelines/jobs/match_merge_vendors.py
CREATE TABLE IF NOT EXISTS FDP_MDM.CURATED.VENDOR_MATCH_GROUPS (
    GOLDEN_RECORD_ID   VARCHAR(36) NOT NULL,
    VENDOR_ID          VARCHAR(10) NOT NULL,
    MATCH_KEY          VARCHAR(64),
    MATCH_RULE         VARCHAR(32),
    SURVIVOR_FLAG      BOOLEAN,
    RUN_ID             VARCHAR(32)
);

