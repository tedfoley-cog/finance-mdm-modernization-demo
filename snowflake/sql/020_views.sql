-- Consumption views used by the Finance Data Platform reporting layer (Power BI, planning cube).
-- The 3-character DIVISION_CODE prefix convention comes from the ERP cost center numbering scheme.

CREATE OR REPLACE VIEW FDP_MDM.CONSUMPTION.VW_COST_CENTER_HIERARCHY AS
SELECT
    d.ENTITY_CODE,
    d.COST_CENTER_CODE,
    d.DESCRIPTION,
    d.PARENT_COST_CENTER_CODE,
    SUBSTR(d.COST_CENTER_CODE, 1, 3)                       AS DIVISION_CODE,
    SUBSTR(d.COST_CENTER_CODE, 4, 3)                       AS DEPARTMENT_SEQ,
    p.DESCRIPTION                                          AS PARENT_DESCRIPTION,
    d.PROFIT_CENTER_CODE,
    d.MANAGER_EMPLOYEE_ID,
    d.STATUS,
    CASE WHEN d.PARENT_COST_CENTER_CODE IS NULL THEN 1 ELSE 2 END AS HIERARCHY_LEVEL
FROM FDP_MDM.CURATED.DIM_COST_CENTER d
LEFT JOIN FDP_MDM.CURATED.DIM_COST_CENTER p
       ON p.ENTITY_CODE = d.ENTITY_CODE
      AND p.COST_CENTER_CODE = d.PARENT_COST_CENTER_CODE;

CREATE OR REPLACE VIEW FDP_MDM.CONSUMPTION.VW_VENDOR_GOLDEN AS
SELECT
    v.GOLDEN_RECORD_ID,
    v.VENDOR_ID,
    v.LEGAL_NAME,
    v.TAX_ID_NORMALIZED,
    v.COUNTRY_CODE,
    v.PAYMENT_TERMS,
    v.DEFAULT_COST_CENTER_CODE,
    cc.DESCRIPTION                                         AS DEFAULT_COST_CENTER_DESCRIPTION,
    v.STATUS,
    v.SOURCE_SYSTEM
FROM FDP_MDM.CURATED.DIM_VENDOR v
LEFT JOIN FDP_MDM.CURATED.DIM_COST_CENTER cc
       ON cc.COST_CENTER_CODE = v.DEFAULT_COST_CENTER_CODE
WHERE v.STATUS = 'ACTIVE';

-- Spend-cube conformed key: entity + 6-digit cost center, zero padded. Downstream planning cube joins on this.
CREATE OR REPLACE VIEW FDP_MDM.CONSUMPTION.VW_COST_CENTER_CONFORMED_KEY AS
SELECT
    ENTITY_CODE,
    COST_CENTER_CODE,
    ENTITY_CODE || '-' || LPAD(COST_CENTER_CODE, 6, '0')   AS CONFORMED_CC_KEY,
    DIVISION_CODE,
    STATUS
FROM FDP_MDM.CONSUMPTION.VW_COST_CENTER_HIERARCHY;

CREATE OR REPLACE VIEW FDP_MDM.CONSUMPTION.VW_VENDOR_DUPLICATE_CANDIDATES AS
SELECT
    TAX_ID_NORMALIZED,
    COUNT(DISTINCT VENDOR_ID)            AS VENDOR_COUNT,
    LISTAGG(VENDOR_ID, ',') WITHIN GROUP (ORDER BY VENDOR_ID) AS VENDOR_IDS
FROM FDP_MDM.CURATED.DIM_VENDOR
WHERE TAX_ID_NORMALIZED IS NOT NULL
GROUP BY TAX_ID_NORMALIZED
HAVING COUNT(DISTINCT VENDOR_ID) > 1;
